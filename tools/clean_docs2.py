# -*- coding: utf-8 -*-
"""玩家向文档第三步：替换掉「稀有度注释 + 影子实现 + 设计自律 + 槽位注册」这一大段开发说明，
并把《第二批名著》表格的表头与单元格对齐。"""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "模组内容总览.md")

START = "> **稀有度（2026-11-05 作者定）**"
END = "> 漏了 Curios 的标签，导致「能拿到、戴不上」——现已补进同一个标签（16 项）。"

REPLACEMENT = """> **稀有度**：书籍饰品统一用稀有度决定名字颜色。
> **史诗（紫）**：自然哲学的数学原理、翠玉录、空白的书页、理想国、堂吉诃德、几何原本、
> 物种起源、本草纲目、梦的解析；其余书籍饰品（含《方块与和平》）为**稀有（青）**。
> 《如我所书》《圣约·原典》《十诫》三本的名字是自己画的渐变色，所以不设稀有度——
> 它们看起来本来就比别的书特别。
>
> **《理想国》的影子**：影子只是本体血条的投影，唯一职责是把打在它身上的伤害等量转给本体。
> 所以它不会触发死亡、掉落、经验、成就与击杀统计，也不参与任何模组的「敌人」清点。
> 同一只本体 8 格内最多存在一份影子，10 秒后自动消散。
> 影子终究是一个真实的实体（这样才能直接借用任意生物的原版模型），所以别的模组仍可能
> 「看到」它——例如刷怪抑制计数、索敌；这些我们无法通用地屏蔽。
>
> **影子允许「双倍伤害」**：调整站位，让剑的横扫在同一轮里同时扫到本体与影子，
> 这一击就该结算两次伤害。为此我们清掉了两处会吞掉第二笔的无敌帧：
> 影子被转伤后不再留无敌帧；先打本体时本体已有的无敌帧也会让影子转来的那笔落地。
> 「先打本体」和「先扫影子」两种顺序都能落下两笔，但同一刀最多两笔、不会三笔。
>
> **九本名著的两条自律**：①不做毕业级数值，它们是「换着戴」的中层饰品，每本都有场景、
> 也都有吃不到的场合；②不做通用加数值（+攻击 +护甲），全部绑一个具体行为，
> 否则戴上之后玩家不会记得自己戴的是哪本。
>
> **tooltip 排版**：书名不写进 tooltip——物品名本身就是书名；分类（哲学/文学/理科）
> 只作内部分组，不上屏。每本书的提示只有三行：一句引语（暗灰斜体）+ 两条机制（青色），
> 没有空行。只有《圣约·原典》与《如我所书》保留自己的标题行。
>
> **《几何原本》不能靠穿脱重置公理**：公理数量与 600 秒计时常驻在玩家身上，
> 摘下只是不再生效，到期才重置，所以「挨一下消耗公理 → 摘下 → 戴上」无法无限回满。
"""


def main():
    with io.open(SRC, encoding="utf-8") as f:
        lines = f.read().split("\n")

    try:
        start = next(i for i, l in enumerate(lines) if l.startswith(START))
        end = next(i for i, l in enumerate(lines) if l.startswith(END))
    except StopIteration:
        print("markers not found")
        return

    lines = lines[:start] + REPLACEMENT.split("\n") + lines[end + 1:]

    text = "\n".join(lines)
    # 两列表格：表头去掉「实现文件」
    text = text.replace("| 书名 | 实现文件 | 机制 |\n| --- | --- | --- |", "| 书名 | 机制 |\n| --- | --- |")
    with io.open(SRC, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    print("replaced lines %d..%d" % (start + 1, end + 1))


if __name__ == "__main__":
    main()
